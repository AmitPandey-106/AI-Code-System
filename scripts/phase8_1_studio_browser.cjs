// Run against phase8_1_studio_smoke.py; only its disposable QA repository is edited.
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const root = process.argv[2], output = path.resolve('eval_results_phase8_1');
  assert(root && path.basename(root).startsWith('litecoder-studio-qa-'));
  const browser = await chromium.launch({channel: 'chrome', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1100}});
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto('http://127.0.0.1:18501');
    await page.locator('#configuredModel').filter({hasText: 'Qwen'}).waitFor();
    await page.locator('#backendStatusText').filter({hasText: 'Backend Online'}).waitFor();
    checks.push('backend health and configured model are visible on a custom proxy port');
    await page.locator('#engineeringOpen').click();
    assert(await page.locator('#engineeringApprove').isDisabled());
    await page.locator('#engineeringTask').fill('Fix f so it returns one');
    await page.locator('#engineeringRoot').fill(root);
    await page.locator('#engineeringCommand').fill('pytest test_mod.py');
    await page.locator('#engineeringStart').click();
    await page.locator('#engineeringState').filter({hasText: 'Awaiting approval'}).waitFor();
    assert.match(fs.readFileSync(path.join(root, 'mod.py'), 'utf8'), /return 0/);
    checks.push('no mutation before approval');
    await page.locator('#engineeringApprove').click();
    await page.locator('#engineeringState').filter({hasText: 'Verified repair'}).waitFor();
    assert.match(fs.readFileSync(path.join(root, 'mod.py'), 'utf8'), /return 1/);
    assert.match(await page.locator('#engineeringTests').innerText(), /"success": true/);
    assert.match(await page.locator('#engineeringDiff').innerText(), /return 1/);
    checks.push('approved repair displays verified success, diff and tests');
    await page.screenshot({path: path.join(output, 'studio_verified_repair.png'), fullPage: true});
    const first = await page.locator('#engineeringSessions').inputValue();
    await page.locator('#engineeringTask').fill('Blocked command');
    await page.locator('#engineeringCommand').fill('python evil.py');
    await page.locator('#engineeringStart').click();
    await page.locator('#engineeringState').filter({hasText: 'Safely rejected by policy'}).waitFor();
    assert(await page.locator('#engineeringApprove').isDisabled());
    checks.push('policy rejection displays failure and disables approval');
    await page.locator('#engineeringSessions').selectOption(first);
    await page.locator('#engineeringState').filter({hasText: 'Verified repair'}).waitFor();
    checks.push('switching sessions restores the selected session evidence');
    fs.writeFileSync(path.join(root, 'mod.py'), 'def f():\n    return 0\n');
    await page.locator('#engineeringTask').fill('Reject this proposed change');
    await page.locator('#engineeringCommand').fill('pytest test_mod.py');
    await page.locator('#engineeringStart').click();
    await page.locator('#engineeringState').filter({hasText: 'Awaiting approval'}).waitFor();
    await page.locator('#engineeringReject').click();
    await page.locator('#engineeringState').filter({hasText: 'Cancelled'}).waitFor();
    assert.match(fs.readFileSync(path.join(root, 'mod.py'), 'utf8'), /return 0/);
    checks.push('rejection cancels without mutation');
    const offlinePage = await browser.newPage();
    offlinePage.on('pageerror', error => errors.push(error.message));
    await offlinePage.route('https://**/*', route => route.abort());
    await offlinePage.goto('http://127.0.0.1:18501');
    await offlinePage.locator('#engineeringOpen').click();
    assert(await offlinePage.locator('#engineeringDialog').isVisible());
    assert(await offlinePage.locator('#engineeringApprove').isDisabled());
    checks.push('engineering panel works without external CDN assets');
    await offlinePage.close();
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'studio_browser_validation.json'), JSON.stringify({status: 'PASS', checks, page_errors: errors}, null, 2));
    console.log(JSON.stringify({status: 'PASS', checks}));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
